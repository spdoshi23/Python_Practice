# arithmatic operators:-
# +  addition
# -  subtraction
# *  multiplication
# /  division
# **  exponential
# // floor Division, whole number after removing decimal
# %  modulus, remainder

m = 15
n = 7
print("addition of", m, "and", n, "is", m+n)
print("subtraction of", m, "and", n, "is", m-n)
print("multiplication of", m, "and", n, "is", m*n)
print("division of", m, "and", n, "is", m/n)
print("floor Division of", m, "and", n, "is", m//n)
print("modulus of", m, "and", n, "is", m%n)
print("exponent of", m, "and", n, "is", m**n)

